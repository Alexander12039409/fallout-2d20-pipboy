    let wType = c[0], modCat = c[1], modName = c[2], effect = c[3];
    let d=0, f=0, r=0, qAdd=[], qRem=[];
    
    if(effect.includes('+1 БК')) d=1; else if(effect.includes('+2 БК')) d=2; else if(effect.includes('+3 БК')) d=3; else if(effect.includes('-1 БК')) d=-1; else if(effect.includes('-2 БК')) d=-2;
