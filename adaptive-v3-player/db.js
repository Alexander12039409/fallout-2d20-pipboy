(function mergeBuiltinItems() {
    if (!masterDB.items) masterDB.items = [];
    const have = new Set(masterDB.items.map(i => i && i.name));
    let added = false;
    dbItems.forEach(it => {
        if (!it || !it.name || have.has(it.name)) return;
        masterDB.items.push(it);
        have.add(it.name);
        added = true;
    });
    if (added) localStorage.setItem('pipboy_master_db', JSON.stringify(masterDB));
})();

