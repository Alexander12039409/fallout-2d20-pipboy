function cleanText(s) {
  return String(s || "")
    .replace(/Псина Уровень[\s\S]*?ОСОБЕННОСТИ/g, "")
    .replace(/ТЕЛО РАЗУМ[\s\S]{0,80}/g, "")
    .replace(/1CDDD|1DCDD|DDDC|CDDD|DCDD/gi, "БК")
    .replace(/\bDC\b/g, "БК")
    .replace(/\bCD\b/g, "БК")
    .replace(/Порочн[а-яё]*/gi, "Жестокий")
    .replace(/ВОС/g, "ВСП")
    .replace(/ЛОВ/g, "ЛВК")
    .replace(/INT/g, "ИНТ")
    .replace(/модИ/g, "модификаций")
    .replace(/\s+/g, " ")
    .trim();
}

function shorten(s, n = 280) {
  s = cleanText(s);
  if (s.length <= n) return s;
  const cut = s.slice(0, n);
  const d = cut.lastIndexOf(". ");
  return (d > 80 ? cut.slice(0, d + 1) : cut.trim()) + (s.length > n ? "…" : "");
}

function parsePerks() {
  const t = fs.readFileSync(kbPath, "utf8");
  const part = t.split("КАТАЛОГ ПЕРКОВ")[1].split("ЧТО НУЖНО ДЛЯ ИГРЫ")[0];
  const blocks = part.split(/\n— /).slice(1);
  const perks = [];
  const seen = new Set();
  for (const b of blocks) {
    const lines = b.trim().split(/\n/);
    let rawName = lines[0].trim().replace(/^P(?=ПАРАЛИЗ)/, "");
    const ranks = (lines.find((l) => l.startsWith("Ранги:")) || "").replace("Ранги:", "").trim();
    let req = (lines.find((l) => l.startsWith("Требования:")) || "").replace("Требования:", "").trim();
    const body = lines.filter((l) => !/^(Ранги:|Требования:|Стр\.)/.test(l)).slice(1).join(" ");
    if (!req || req === "None") {
      const m = body.match(/^(СИЛ|ВСП|ВОС|ВЫН|ХАР|ИНТ|ЛОВ|ЛВК|УДЧ|INT)\s+\d+[^.]*?(?=\s+Когда|\s+Вы |\s+Добавьте|\s+Увеличьте)/);
      if (!req || req === "None") req = req === "None" ? "Нет" : req;
      if ((!req || req === "Нет") && m) req = m[1] + m[0].slice(m[1].length);
    }
    req = cleanText(req).replace(/^None$/i, "Нет").replace(/,\s*$/, "");
    if (ranks && ranks !== "1") req = (req && req !== "Нет" ? req + ", " : "") + "Ранги " + ranks;
    const name = NAME_MAP[rawName] || rawName.replace(/Ё/g, "Е");
    if (seen.has(name)) continue;
    seen.add(name);
    perks.push({ name, desc: shorten(body, 320), reqStr: req || "Нет" });
  }
  const extras = [
    { name: "Высшая лига", desc: "Двуручное оружие ближнего боя получает свойство Жестокий.", reqStr: "СИЛ 8" },
    { name: "Это можно!", desc: "+1 случайная еда при поиске ресурсов, не тратя ОД.", reqStr: "УДЧ 5" }
  ];
  extras.forEach((p) => { if (!seen.has(p.name)) perks.push(p); });
  return perks;
}

function j(obj) {
  return JSON.stringify(obj, null, 4).replace(/"([^"]+)":/g, "$1:");
}

