function weaponSlotAllowed(wName, slot) {
    const allowed = WEAPON_ALLOWED_SLOTS[wName];
    if (!allowed) return false;
    return allowed.indexOf(slot) !== -1;
}
function weaponModNameAllowed(wName, modCat, modName) {
    if (CALIBER_ONLY[modName] && CALIBER_ONLY[modName].indexOf(wName) === -1) return false;
    if (modCat === 'Ресивер' && modName === 'Автоматический' && NO_AUTO_RECEIVER[wName]) return false;
    if (wName === 'Лазерный мушкет' && modCat === 'Конденсатор') return false;
    if (wName === 'Гамма-пушка') return false;
    return true;
}
function sharedModTypeOk(wType, cat, modCat, wName) {
    if (wType === 'Холодное' || wType === 'Меч' || wType === 'Кастет/Бита' || wType === 'Гатлинг' || wType === 'Тяжелое') return false;
    if (wType === 'Стрелковое') {
        if (cat === 'Стрелковое') return true;
        if (cat === 'Энергетическое' && (modCat === 'Прицел' || modCat === 'Приклад' || modCat === 'Рукоять')) return true;
        return false;
    }
    if (wType === 'Энергетическое') return cat === 'Энергетическое' && wName !== 'Гамма-пушка';
    return false;
}

