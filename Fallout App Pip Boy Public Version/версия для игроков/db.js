(function mergeBuiltinCatalog() {
    let added = false;
    if (!masterDB.items) masterDB.items = [];
    if (!masterDB.perks) masterDB.perks = [];
    if (!masterDB.weapons) masterDB.weapons = {};
    const dropItems = { 'Стимулятор': 1, 'Рейдерский понож/наруч': 1, 'Кожаный понож/наруч': 1 };
    const haveItem = new Set(masterDB.items.map(i => i && i.name));
    dbItems.forEach(it => {
        if (!it || !it.name || haveItem.has(it.name)) return;
        masterDB.items.push(it);
        haveItem.add(it.name);
        added = true;
    });
    const havePerk = new Set(masterDB.perks.map(p => p && p.name));
    dbPerks.forEach(p => {
        if (!p || !p.name || havePerk.has(p.name)) return;
        masterDB.perks.push(p);
        havePerk.add(p.name);
        added = true;
    });
    Object.keys(weaponDB.weapons).forEach(name => {
        const src = weaponDB.weapons[name];
        if (!masterDB.weapons[name]) {
            masterDB.weapons[name] = src;
            added = true;
            return;
        }
        const dst = masterDB.weapons[name];
        if (!dst.slots) dst.slots = {};
        Object.keys(src.slots || {}).forEach(slot => {
            if (!dst.slots[slot]) {
                dst.slots[slot] = src.slots[slot];
                added = true;
                return;
            }
            const have = new Set(dst.slots[slot].map(m => m && m.name));
            (src.slots[slot] || []).forEach(m => {
                if (!m || !m.name) return;
                const existing = dst.slots[slot].find(x => x && x.name === m.name);
                if (existing) {
                    if (m.prefix != null && existing.prefix !== m.prefix) {
                        existing.prefix = m.prefix;
                        added = true;
                    }
                    return;
                }
                dst.slots[slot].push(m);
                have.add(m.name);
                added = true;
            });
        });
    });
    if (masterDB.libVersion !== BUILTIN_DB_VERSION) {
        Object.keys(weaponDB.weapons).forEach(name => {
            masterDB.weapons[name] = weaponDB.weapons[name];
        });
        dbPerks.forEach(p => {
            const i = masterDB.perks.findIndex(x => x && x.name === p.name);
            if (i >= 0) masterDB.perks[i] = { name: p.name, desc: p.desc, reqStr: p.reqStr };
        });
        dbItems.forEach(it => {
            const i = masterDB.items.findIndex(x => x && x.name === it.name);
            if (i >= 0) {
                masterDB.items[i].desc = it.desc;
                masterDB.items[i].type = it.type;
                masterDB.items[i].category = it.category;
            }
        });
        const seenItem = new Set();
        masterDB.items = masterDB.items.filter(i => {
            if (!i || !i.name || dropItems[i.name]) return false;
            if (seenItem.has(i.name)) return false;
            seenItem.add(i.name);
            return true;
        });
        const seenPerk = new Set();
        masterDB.perks = masterDB.perks.filter(p => {
            if (!p || !p.name) return false;
            if (seenPerk.has(p.name)) return false;
            seenPerk.add(p.name);
            return true;
        });
        masterDB.libVersion = BUILTIN_DB_VERSION;
        added = true;
    }
    if (added) localStorage.setItem('pipboy_master_db', JSON.stringify(masterDB));
})();

