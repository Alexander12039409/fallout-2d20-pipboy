let helpCurrentId = HELP_SECTIONS[0].id;

function closeHelpNav() {
    const layout = document.querySelector('.help-layout');
    if (layout) layout.classList.remove('nav-open');
}

function openHelpNav() {
    const layout = document.querySelector('.help-layout');
    if (layout) layout.classList.add('nav-open');
}

function toggleHelpNav() {
    const layout = document.querySelector('.help-layout');
    if (!layout) return;
    layout.classList.toggle('nav-open');
}

function showHelpSection(id) {
    const section = HELP_SECTIONS.find(s => s.id === id) || HELP_SECTIONS[0];
    helpCurrentId = section.id;
    const body = document.getElementById('help-body');
    if (body) {
        body.innerHTML = `<h2 class="help-h">${section.title}</h2>${section.html}`;
        body.scrollTop = 0;
    }
    document.querySelectorAll('.help-nav-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-help') === section.id);
        if (btn.classList.contains('active') && btn.scrollIntoView) {
            btn.scrollIntoView({ inline: 'center', block: 'nearest', behavior: 'smooth' });
        }
    });
    closeHelpNav();
}

function initHelp() {
    const nav = document.getElementById('help-nav-list');
    if (!nav) return;
    nav.innerHTML = '';
    HELP_SECTIONS.forEach(section => {
        const btn = document.createElement('button');
        btn.type = 'button';
        btn.className = 'help-nav-btn';
        btn.setAttribute('data-help', section.id);
        btn.textContent = section.title;
        btn.onclick = () => showHelpSection(section.id);
        nav.appendChild(btn);
    });
    showHelpSection(helpCurrentId);
}

initHelp();
